// Builds reactions/geometry.js from the PubChem 3D conformer SDF files in
// reactions/sdf/. Coordinates are copied from PubChem, never typed by hand.
//
//   node reactions/build-geometry.mjs          (rewrite geometry.js)
//   node reactions/build-geometry.mjs --check  (fail if geometry.js is stale)
//
// SDF files were fetched from PubChem PUG REST:
//   https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/<CID>/SDF?record_type=3d
//
// H2 is the one exception. PubChem has no 3D conformer for CID 783
// (PUG REST answers 404), so H2 is built from its single measured
// value, the H–H distance r_e = 0.7414 Å (NIST CCCBDB, Huber & Herzberg 1979).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCES = [
  { id: "O2", name: "Oxygen", cid: 977, file: "oxygen.sdf" },
  { id: "H2O", name: "Water", cid: 962, file: "water.sdf" },
  { id: "CH4", name: "Methane", cid: 297, file: "methane.sdf" },
  { id: "CO2", name: "Carbon dioxide", cid: 280, file: "co2.sdf" },
  { id: "H2O2", name: "Hydrogen peroxide", cid: 784, file: "h2o2.sdf" },
];

function parseSdf(text) {
  const lines = text.split(/\r?\n/);
  const counts = lines[3];
  const nAtoms = Number(counts.slice(0, 3));
  const nBonds = Number(counts.slice(3, 6));
  const atoms = [];
  for (let i = 0; i < nAtoms; i++) {
    const l = lines[4 + i];
    atoms.push({
      el: l.slice(31, 34).trim(),
      x: Number(l.slice(0, 10)),
      y: Number(l.slice(10, 20)),
      z: Number(l.slice(20, 30)),
    });
  }
  const bonds = [];
  for (let j = 0; j < nBonds; j++) {
    const l = lines[4 + nAtoms + j];
    bonds.push([Number(l.slice(0, 3)) - 1, Number(l.slice(3, 6)) - 1, Number(l.slice(6, 9))]);
  }
  const cidLine = lines.indexOf("> <PUBCHEM_COMPOUND_CID>");
  return { atoms, bonds, cid: Number(lines[cidLine + 1]) };
}

const out = {};
for (const s of SOURCES) {
  const g = parseSdf(readFileSync(join(here, "sdf", s.file), "utf8"));
  if (g.cid !== s.cid) throw new Error(`${s.file}: CID ${g.cid} != ${s.cid}`);
  out[s.id] = {
    name: s.name,
    source: `PubChem CID ${s.cid} 3D conformer`,
    atoms: g.atoms.map((a) => [a.el, a.x, a.y, a.z]),
    bonds: g.bonds,
  };
}
out.H2 = {
  name: "Hydrogen",
  source: "PubChem CID 783 has no 3D conformer; H–H r_e 0.7414 Å from NIST CCCBDB",
  atoms: [["H", -0.3707, 0, 0], ["H", 0.3707, 0, 0]],
  bonds: [[0, 1, 1]],
};

const js =
  "// Generated by reactions/build-geometry.mjs from PubChem 3D conformer SDF files.\n" +
  "// Do not edit by hand. Units: ångström. bonds: [i, j, order].\n" +
  "export const GEOMETRY = " + JSON.stringify(out, null, 1) + ";\n";
const target = join(here, "geometry.js");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== js) { console.error("geometry.js is stale"); process.exit(1); }
  console.log("geometry.js matches the SDF files");
} else {
  writeFileSync(target, js);
  console.log("wrote", target);
}
