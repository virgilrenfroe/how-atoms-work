// Builds acids/geometry.js from the PubChem 3D conformer SDF files in
// acids/sdf/. Coordinates are copied from PubChem, never typed by hand.
//
//   node acids/build-geometry.mjs          (rewrite geometry.js)
//   node acids/build-geometry.mjs --check  (fail if geometry.js is stale)
//
// SDF files were fetched from PubChem PUG REST:
//   https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/<CID>/SDF?record_type=3d
//
// Monoatomic ions Na⁺ and Cl⁻ have no molecular conformer; they are drawn
// as single spheres from Shannon ionic radii (documented in NOTES.md).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCES = [
  { id: "HCl", name: "Hydrogen chloride", cid: 313, file: "hcl.sdf" },
  { id: "H2O", name: "Water", cid: 962, file: "h2o.sdf" },
  { id: "H3O", name: "Hydronium", cid: 123332, file: "h3o.sdf" },
  { id: "OH", name: "Hydroxide", cid: 961, file: "oh.sdf" },
  { id: "CH3COOH", name: "Acetic acid", cid: 176, file: "acetic.sdf" },
];

function parseSdf(text) {
  const lines = text.split(/\r?\n/);
  const counts = lines[3];
  const nAtoms = Number(counts.slice(0, 3));
  const nBonds = Number(counts.slice(3, 6));
  const atoms = [];
  for (let i = 0; i < nAtoms; i++) {
    const l = lines[4 + i];
    atoms.push({
      el: l.slice(31, 34).trim(),
      x: Number(l.slice(0, 10)),
      y: Number(l.slice(10, 20)),
      z: Number(l.slice(20, 30)),
    });
  }
  const bonds = [];
  for (let j = 0; j < nBonds; j++) {
    const l = lines[4 + nAtoms + j];
    bonds.push([Number(l.slice(0, 3)) - 1, Number(l.slice(3, 6)) - 1, Number(l.slice(6, 9))]);
  }
  const cidLine = lines.indexOf("> <PUBCHEM_COMPOUND_CID>");
  return { atoms, bonds, cid: Number(lines[cidLine + 1]) };
}

const out = {};
for (const s of SOURCES) {
  const g = parseSdf(readFileSync(join(here, "sdf", s.file), "utf8"));
  if (g.cid !== s.cid) throw new Error(`${s.file}: CID ${g.cid} != ${s.cid}`);
  out[s.id] = {
    name: s.name,
    source: `PubChem CID ${s.cid} 3D conformer`,
    atoms: g.atoms.map((a) => [a.el, a.x, a.y, a.z]),
    bonds: g.bonds,
  };
}

const js =
  "// Generated by acids/build-geometry.mjs from PubChem 3D conformer SDF files.\n" +
  "// Do not edit by hand. Units: ångström. bonds: [i, j, order].\n" +
  "export const GEOMETRY = " + JSON.stringify(out, null, 1) + ";\n";
const target = join(here, "geometry.js");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== js) { console.error("geometry.js is stale"); process.exit(1); }
  console.log("geometry.js matches the SDF files");
} else {
  writeFileSync(target, js);
  console.log("wrote", target);
}
